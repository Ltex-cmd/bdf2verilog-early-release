#!/usr/bin/env python3
"""Original, deterministic synthetic fixtures; no external corpus or vendor assets."""
import argparse, hashlib, json
from pathlib import Path
HEADER = '(header "graphic" (version "1.4"))\n'
def pin(direction, name, x, y=8):
    return f'(pin ({direction}) (rect {x} {y-8} {x+168} {y+8}) (text "{direction.upper()}") (text "{name}") (pt 0 8))\n'
def wire(x, end, y=8, bus=False):
    return f'(connector (pt {x} {y}) (pt {end} {y})'+(' (bus)' if bus else '')+')\n'
def generate(destination):
    destination.mkdir(parents=True, exist_ok=True)
    cases=[]
    def save(name, family, size, text, children=None, outputs=None):
        folder=destination/name; folder.mkdir(exist_ok=True)
        (folder/f'{name}.bdf').write_text(HEADER+text)
        for child, body in (children or {}).items(): (folder/child).write_text(HEADER+body)
        width=32 if '32bit' in family else 1
        outputs=outputs or ['Y']
        declarations='\n'.join(f'wire [{width-1}:0] {name};' for name in outputs)
        ports=', '.join(f'.{name}({name})' for name in outputs)
        checks=' '.join(f'if ({name} !== value) $fatal(1, "identity mismatch {name}");' for name in outputs)
        (folder/'check.v').write_text(f'''// Original independent identity oracle for the generated pass-through circuit.
module identity_tb;
reg [{width-1}:0] A;
{declarations}
{name} dut(.A(A), {ports});
task check;
input [{width-1}:0] value;
begin A=value; #1; {checks} end
endtask
initial begin
check('0); check('1); check(32'h55555555); check(32'haaaaaaaa);
check('x); check('z);
$display("identity oracle passed"); $finish;
end
endmodule
''')
        cases.append({'name':name,'family':family,'size':size,'top':f'{name}/{name}.bdf','expected':'Every output equals A', 'files':{str(p.relative_to(destination)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(folder.glob('*.bdf'))}})
    for n in (128,512,2048):
        save(f'flat_{n}','flat_scalar_chain',n,pin('input','A',0)+pin('output','Y',n)+''.join(wire(i,i+1) for i in range(n)))
    for n in (16,64,256):
        text=pin('input','A',0)+pin('output','Y',n*80)
        for i in range(n):
            x=i*80+20
            text+=f'(symbol (rect {x} 0 {x+40} 16) (text "leaf") (text "stage{i}") (port (input) (pt 0 8) (text "A")) (port (output) (pt 40 8) (text "Y")))\n'
            text+=wire(i*80,x)+wire(x+40,(i+1)*80)
        save(f'hierarchy_{n}','hierarchy_repeated_leaf',n,text,{'leaf.bdf':pin('input','A',0)+pin('output','Y',40)+wire(0,40)})
    for n in (64,256,1024):
        save(f'bus_contacts_{n}','bus_chain_contacts_32bit',n,pin('input','A[31..0]',0)+pin('output','Y[31..0]',n)+''.join(wire(i,i+1,bus=True) for i in range(n)))
        # Scalar terminals force bus-contact classification; vector terminals
        # bypass that path. Every scalar point hits the first labeled segment.
        outputs=[f'Y{i}' for i in range(n)]
        text=pin('input','A',0)+''.join(pin('output',name,i+1) for i,name in enumerate(outputs))
        text+=''.join(f'(connector (pt 0 8) (pt {2*n+2+i} 8) (bus) (text "net"))\n' for i in range(n))
        save(f'dense_early_hit_{n}','dense_bus_scalar_early_hit',n,text,outputs=outputs)
    (destination/'manifest.json').write_text(json.dumps({'generator_version':1,'provenance':'Original synthetic source generated by generate.py for early-release; no external source inputs.', 'cases':cases},indent=2)+'\n')
    return cases
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('destination',type=Path);a=p.parse_args();generate(a.destination)
